"""Run the Week-1 corpus evaluation through DispatchDesk production services."""

from __future__ import annotations

import argparse
import csv
import json
import os
import re
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))


def load_local_env() -> None:
    """Load ignored project env files for a root-level runner invocation."""
    for path in (BACKEND / ".env", ROOT / ".env"):
        if not path.exists():
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            os.environ.setdefault(key.strip(), value.strip().strip("\"'"))
        break


def read_dataset() -> dict[str, Any]:
    dataset = json.loads((ROOT / "evals/data/gold_dataset.json").read_text())
    from service.chunker import load_corpus
    from service.ingestion import BACKEND_DIR, CORPUS_DIR

    documents, _slug_ids = load_corpus(CORPUS_DIR, BACKEND_DIR)
    per_document_ordinal: dict[str, int] = {}
    valid_ids: set[str] = set()
    for document in documents:
        doc_id = document.metadata["doc_id"]
        ordinal = per_document_ordinal.get(doc_id, 0)
        valid_ids.add(f"{doc_id}#{ordinal}")
        per_document_ordinal[doc_id] = ordinal + 1
    for case in dataset["cases"]:
        for chunk_id in case.get("expected_chunk_ids", []) + case.get(
            "relevant_chunk_ids", []
        ):
            if chunk_id not in valid_ids:
                raise ValueError(
                    f"{case['id']} references chunk ID not generated by production ingestion: {chunk_id}"
                )
    return dataset


def git_commit() -> str | None:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None


def _csv_value(value: Any) -> Any:
    if value is None:
        return ""
    if isinstance(value, (list, dict)):
        return json.dumps(value, ensure_ascii=False)
    return value


def _rate_limit_retry_seconds(error: Exception, attempt: int) -> float:
    """Read Groq's retry hint when present; otherwise use short backoff."""
    match = re.search(r"try again in\s+(\d+(?:\.\d+)?)\s*s", str(error), re.IGNORECASE)
    return float(match.group(1)) + 0.3 if match else (2**attempt) + 0.3


def write_gold_csv(dataset: dict[str, Any], output: Path) -> None:
    """Export the canonical gold JSON cases as a spreadsheet-friendly CSV."""
    fieldnames = [
        "dataset_version",
        "corpus_revision",
        "id",
        "category",
        "question",
        "expected_chunk_ids",
        "relevant_chunk_ids",
        "must_include",
        "must_not_include",
        "safety_required_include",
        "safety_prohibited",
        "requires_live_data",
        "safety_sensitive",
        "retrieval_evaluation",
        "expected_behavior",
        "allowed_operational_values",
    ]
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fieldnames)
        writer.writeheader()
        for case in dataset["cases"]:
            writer.writerow(
                {
                    "dataset_version": dataset["dataset_version"],
                    "corpus_revision": dataset["corpus_revision"],
                    **{key: _csv_value(case.get(key)) for key in fieldnames[2:]},
                }
            )


def write_results_csv(result: dict[str, Any], output: Path) -> None:
    """Write overall metric rows and detailed per-case evaluation rows."""
    case_fieldnames = [
        "record_type",
        "timestamp",
        "git_commit",
        "dataset",
        "dataset_version",
        "corpus_revision",
        "metric",
        "value",
        "evaluation_status",
        "case_id",
        "category",
        "query",
        "gold_chunk_ids",
        "retrieved_chunk_ids",
        "similarities",
        "first_relevant_rank",
        "error",
    ]
    answer_fieldnames = [
        "answer",
        "passed",
        "reasons",
        "requires_live_data",
        "live_data_passed",
        "safety_sensitive",
        "safety_passed",
        "unsupported_numeric_claims",
        "manual_review",
    ]
    fieldnames = case_fieldnames + (
        [] if result.get("retrieval_only") else answer_fieldnames
    )
    common = {
        "timestamp": result.get("timestamp"),
        "git_commit": result.get("git_commit"),
        "dataset": result.get("dataset"),
        "dataset_version": result.get("dataset_version"),
        "corpus_revision": result.get("corpus_revision"),
    }
    rows: list[dict[str, Any]] = []
    for group, metrics in result.get("metrics", {}).items():
        if group == "retrieval" and metrics is None:
            metric_rows = [(f"recall@{k}", None) for k in (1, 3, 5)] + [("mrr", None)]
            prefix = "retrieval."
        elif isinstance(metrics, dict):
            metric_rows = metrics.items()
            prefix = f"{group}."
        else:
            metric_rows = [(group, metrics)]
            prefix = ""
        for name, value in metric_rows:
            rows.append(
                {
                    "record_type": "overall_metric",
                    **common,
                    "metric": f"{prefix}{name}",
                    "value": _csv_value(value),
                    "evaluation_status": "available"
                    if value is not None
                    else "unavailable",
                }
            )

    for case in result.get("per_case", []):
        retrieval = case.get("retrieval", {})
        errors = []
        retrieval_status = case.get("retrieval_status", {})
        retrieval_error = retrieval.get("error") or retrieval_status.get("error")
        if retrieval_error:
            errors.append(f"retrieval: {retrieval_error}")
        answer_eval = case.get("answer_evaluation", {})
        if not result.get("retrieval_only") and answer_eval.get("error"):
            errors.append(f"answer: {answer_eval['error']}")
        result_columns = {
            "record_type": "case_result",
            **common,
            "evaluation_status": "failed" if errors else "complete",
            "case_id": case.get("id"),
            "category": case.get("category"),
            "query": case.get("question"),
            "gold_chunk_ids": _csv_value(retrieval.get("gold_chunk_ids")),
            "retrieved_chunk_ids": _csv_value(retrieval.get("retrieved_chunk_ids")),
            "similarities": _csv_value(retrieval.get("similarities")),
            "first_relevant_rank": retrieval.get("first_relevant_rank"),
            "error": " | ".join(errors),
        }
        if not result.get("retrieval_only"):
            result_columns.update(
                {
                    "answer": case.get("answer"),
                    "passed": answer_eval.get("passed"),
                    "reasons": _csv_value(answer_eval.get("reasons")),
                    "requires_live_data": case.get("requires_live_data"),
                    "live_data_passed": case.get("live_data_evaluation", {}).get(
                        "passed"
                    ),
                    "safety_sensitive": case.get("safety_sensitive"),
                    "safety_passed": case.get("safety_evaluation", {}).get("passed"),
                    "unsupported_numeric_claims": _csv_value(
                        case.get("unsupported_claim_evaluation", {}).get(
                            "unsupported_numeric_claims"
                        )
                    ),
                    "manual_review": case.get("unsupported_claim_evaluation", {}).get(
                        "manual_review"
                    ),
                }
            )
        rows.append(result_columns)

    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def case_is_complete(
    record: dict[str, Any], case: dict[str, Any], retrieval_only: bool
) -> bool:
    """Whether a checkpoint contains every successful result required for a case."""
    needs_retrieval = case.get(
        "retrieval_evaluation", bool(case.get("relevant_chunk_ids"))
    )
    status = record.get("retrieval_status", {})
    retrieval_ok = status.get("success")
    if retrieval_ok is None:
        # Compatibility for older results files that predate retrieval_status.
        retrieval = record.get("retrieval", {})
        retrieval_ok = not retrieval.get("error") and (
            bool(retrieval) or not needs_retrieval
        )
    if retrieval_only:
        return not needs_retrieval or bool(retrieval_ok)
    answer = record.get("answer_evaluation", {})
    return bool(retrieval_ok) and bool(answer) and not answer.get("error")


def write_checkpoint(result: dict[str, Any], json_path: Path, csv_path: Path) -> None:
    """Atomically persist JSON and CSV after each completed evaluation case."""
    json_path.parent.mkdir(parents=True, exist_ok=True)
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    json_tmp = json_path.with_suffix(json_path.suffix + ".tmp")
    csv_tmp = csv_path.with_suffix(csv_path.suffix + ".tmp")
    json_tmp.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n")
    write_results_csv(result, csv_tmp)
    json_tmp.replace(json_path)
    csv_tmp.replace(csv_path)


def evaluate(args: argparse.Namespace) -> dict[str, Any]:
    load_local_env()
    from metrics import recall_at_k, reciprocal_rank

    if not args.retrieval_only:
        from metrics import (
            aggregate_rate,
            answer_checks,
            live_data_check,
            safety_check,
            unsupported_numeric_claims,
        )

    from service.embedder import embed_texts
    from service.vector_store import get_supabase_client, retrieve

    if not args.retrieval_only:
        from service.rag import answer_question

    dataset = read_dataset()
    write_gold_csv(dataset, ROOT / "evals/data/gold_dataset.csv")
    cases = dataset["cases"][: args.limit or None]
    gold_by_id = {case["id"]: case for case in cases}
    records_by_id: dict[str, dict[str, Any]] = {}
    if args.resume and args.output.exists():
        prior = json.loads(args.output.read_text(encoding="utf-8"))
        if prior.get("dataset_version") != dataset["dataset_version"]:
            raise ValueError(
                "Cannot resume results from a different dataset version; run without --resume to start over."
            )
        prior_retrieval_only = prior.get("retrieval_only")
        can_reuse_full_run_for_retrieval = (
            args.retrieval_only and prior_retrieval_only is False
        )
        if (
            prior_retrieval_only != args.retrieval_only
            and not can_reuse_full_run_for_retrieval
        ) or prior.get("retrieval_top_k") != args.top_k:
            raise ValueError(
                "Cannot resume with different evaluation options; run without --resume to start over."
            )
        for record in prior.get("per_case", []):
            case = gold_by_id.get(record.get("id"))
            if case and case_is_complete(record, case, args.retrieval_only):
                records_by_id[record["id"]] = record
    elif args.resume:
        print("No saved results found; starting from the first case.", flush=True)

    if args.resume:
        for case_index, case in enumerate(cases, start=1):
            if case["id"] in records_by_id:
                print(
                    f"[{case_index}/{len(cases)}] {case['id']}: already complete; skipping",
                    flush=True,
                )

    client = get_supabase_client()
    top_count = max(args.top_k, 5)

    def current_result() -> dict[str, Any]:
        per_case = [
            records_by_id[case["id"]] for case in cases if case["id"] in records_by_id
        ]
        retrieval_rows = [
            record["retrieval"]
            for record in per_case
            if gold_by_id[record["id"]].get(
                "retrieval_evaluation",
                bool(gold_by_id[record["id"]].get("relevant_chunk_ids")),
            )
            and record.get("retrieval")
            and not record["retrieval"].get("error")
        ]
        retrieval_metrics = None
        if retrieval_rows:
            retrieval_metrics = {
                f"recall@{k}": sum(row["recall_at"][str(k)] for row in retrieval_rows)
                / len(retrieval_rows)
                for k in (1, 3, 5)
            }
            retrieval_metrics["mrr"] = sum(
                row["reciprocal_rank"] for row in retrieval_rows
            ) / len(retrieval_rows)
        metrics = {"retrieval": retrieval_metrics}
        if not args.retrieval_only:
            answer_rows = [
                record["answer_evaluation"]
                for record in per_case
                if record.get("answer_evaluation")
                and not record["answer_evaluation"].get("error")
            ]
            live_rows = [
                record["live_data_evaluation"]
                for record in per_case
                if record.get("live_data_evaluation")
            ]
            safety_rows = [
                record["safety_evaluation"]
                for record in per_case
                if record.get("safety_evaluation")
            ]
            unsupported_rows = [
                record["unsupported_claim_evaluation"]
                for record in per_case
                if record.get("unsupported_claim_evaluation")
                and not record.get("answer_evaluation", {}).get("error")
            ]
            prohibited_rows = [
                {
                    "id": record["id"],
                    "passed": not any(
                        reason.startswith("contains prohibited claim:")
                        for reason in record.get("safety_evaluation", {}).get(
                            "reasons", []
                        )
                    ),
                }
                for record in per_case
                if record.get("safety_evaluation")
            ]
            metrics.update(
                {
                    "answer_pass_rate": aggregate_rate(answer_rows),
                    "live_data_pass_rate": aggregate_rate(live_rows),
                    "safety_compliance_rate": aggregate_rate(safety_rows),
                    "unsupported_claim_rate": (
                        1 - aggregate_rate(unsupported_rows)
                        if unsupported_rows
                        else None
                    ),
                    "prohibited_claim_rate": (
                        1 - aggregate_rate(prohibited_rows) if prohibited_rows else None
                    ),
                    "unsupported_or_prohibited_claim_rate": _combined_claim_rate(
                        unsupported_rows, prohibited_rows
                    ),
                }
            )
        retrieval_failed = sum(
            bool(record.get("retrieval_status", {}).get("attempted"))
            and not record.get("retrieval_status", {}).get("success")
            for record in per_case
            if gold_by_id[record["id"]].get(
                "retrieval_evaluation",
                bool(gold_by_id[record["id"]].get("relevant_chunk_ids")),
            )
        )
        retrieval_total = sum(
            bool(case.get("retrieval_evaluation", bool(case.get("relevant_chunk_ids"))))
            for case in cases
        )
        answer_rows = [
            record.get("answer_evaluation")
            for record in per_case
            if record.get("answer_evaluation")
            and not record["answer_evaluation"].get("error")
        ]
        answer_failed = sum(
            bool(record.get("answer_evaluation", {}).get("error"))
            for record in per_case
        )
        return {
            "timestamp": datetime.now(UTC).isoformat(),
            "git_commit": git_commit(),
            "dataset": "evals/data/gold_dataset.json",
            "dataset_version": dataset["dataset_version"],
            "corpus_revision": dataset["corpus_revision"],
            "retrieval_top_k": args.top_k,
            "retrieval_only": args.retrieval_only,
            "resume": args.resume,
            "evaluation_summary": {
                "total_cases": len(cases),
                "cases_written": len(per_case),
                "retrieval_succeeded": len(retrieval_rows),
                "retrieval_failed": retrieval_failed,
                "retrieval_pending": max(
                    0, retrieval_total - len(retrieval_rows) - retrieval_failed
                ),
                **(
                    {
                        "answers_succeeded": len(answer_rows),
                        "answers_failed": answer_failed,
                        "answers_pending": max(
                            0, len(cases) - len(answer_rows) - answer_failed
                        ),
                    }
                    if not args.retrieval_only
                    else {}
                ),
            },
            "metrics": metrics,
            "per_case": per_case,
            **(
                {
                    "manual_review_cases": [
                        row["id"] for row in unsupported_rows if row["manual_review"]
                    ]
                }
                if not args.retrieval_only
                else {}
            ),
        }

    for case_index, case in enumerate(cases, start=1):
        progress_prefix = f"[{case_index}/{len(cases)}] {case['id']}"
        if case["id"] in records_by_id:
            continue
        print(f"{progress_prefix} {case['category']}: started", flush=True)
        relevant = case.get("relevant_chunk_ids", [])
        retrieved: list[dict[str, Any]] = []
        retrieval_error = None
        # Retrieval-only runs skip cases without gold retrieval evidence.
        should_retrieve = not args.retrieval_only or case.get(
            "retrieval_evaluation", bool(relevant)
        )
        if should_retrieve:
            try:
                embedding = embed_texts([case["question"]])[0]
                retrieved = retrieve(
                    client=client,
                    query_embedding=embedding,
                    match_count=top_count,
                )
            except Exception as exc:  # noqa: BLE001 - preserve partial run diagnostics
                retrieval_error = f"{type(exc).__name__}: {exc}"

            ids = [str(row["chunk_id"]) for row in retrieved]
            if retrieval_error:
                ids = []
            first_rank = next(
                (rank for rank, chunk_id in enumerate(ids, 1) if chunk_id in relevant),
                None,
            )
            retrieval_row = {
                "id": case["id"],
                "query": case["question"],
                "gold_chunk_ids": relevant,
                "retrieved_chunk_ids": ids[: args.top_k],
                "similarities": [
                    row.get("similarity") for row in retrieved[: args.top_k]
                ],
                "first_relevant_rank": first_rank,
                "recall_at": {str(k): recall_at_k(ids, relevant, k) for k in (1, 3, 5)},
                "reciprocal_rank": reciprocal_rank(ids, relevant),
                "error": retrieval_error,
            }
            is_retrieval_eval = case.get("retrieval_evaluation", bool(relevant))
            if not is_retrieval_eval:
                retrieval_row = None
            if is_retrieval_eval:
                retrieval_status = (
                    f"failed ({retrieval_error.split(':', 1)[0]})"
                    if retrieval_error
                    else f"complete (first relevant rank: {first_rank or 'none'})"
                )
                print(f"{progress_prefix} retrieval: {retrieval_status}", flush=True)
            else:
                print(
                    f"{progress_prefix} retrieval: context ready (excluded from retrieval scoring)",
                    flush=True,
                )
        else:
            retrieval_row = None
            print(
                f"{progress_prefix} retrieval: skipped (no gold evidence)", flush=True
            )

        record: dict[str, Any] = {
            "id": case["id"],
            "category": case["category"],
            "question": case["question"],
            "requires_live_data": case.get("requires_live_data", False),
            "safety_sensitive": case.get("safety_sensitive", False),
            "retrieval_status": {
                "attempted": should_retrieve,
                "success": not retrieval_error,
                "error": retrieval_error,
            },
        }
        if retrieval_row is not None:
            record["retrieval"] = retrieval_row
        # Persist the retrieval result immediately after it is produced.
        records_by_id[case["id"]] = record
        write_checkpoint(current_result(), args.output, args.results_csv)

        if not args.retrieval_only:
            print(f"{progress_prefix} answer generation: started", flush=True)
            answer_error = None
            for attempt in range(3):
                try:
                    # Match the production default (three context chunks);
                    # retrieval metrics still use the configured top K.
                    answer = answer_question(
                        case["question"],
                        top_k=3,
                        retrieved_results=retrieved[:3],
                    )
                    break
                except Exception as exc:  # noqa: BLE001 - partial run diagnostics
                    if "RateLimitError" in type(exc).__name__ and attempt < 2:
                        delay = _rate_limit_retry_seconds(exc, attempt)
                        print(
                            f"{progress_prefix} answer generation: rate limited; retrying in {delay:.1f}s ({attempt + 1}/2)",
                            flush=True,
                        )
                        time.sleep(delay)
                        continue
                    answer = ""
                    answer_error = f"{type(exc).__name__}: {exc}"
                    break
            answer_result = answer_checks(case, answer)
            answer_result.update({"id": case["id"], "error": answer_error})
            answer_status = (
                f"failed ({answer_error.split(':', 1)[0]})"
                if answer_error
                else f"complete (criteria {'passed' if answer_result['passed'] else 'failed'})"
            )
            print(f"{progress_prefix} answer generation: {answer_status}", flush=True)
            record["answer"] = answer
            record["answer_evaluation"] = answer_result

            if case.get("requires_live_data") and not answer_error:
                context = "\n\n".join(row.get("content", "") for row in retrieved)
                live_result = live_data_check(answer, case, context)
                live_result["id"] = case["id"]
                record["live_data_evaluation"] = live_result

            if case.get("safety_sensitive") and not answer_error:
                safety_result = safety_check(case, answer)
                safety_result["id"] = case["id"]
                record["safety_evaluation"] = safety_result

            context = "\n\n".join(row.get("content", "") for row in retrieved)
            claims = unsupported_numeric_claims(answer, context)
            unsupported_result = {
                "id": case["id"],
                "passed": not claims,
                "unsupported_numeric_claims": claims,
                "manual_review": bool(claims),
                "note": "Numeric grounding heuristic only; non-numeric claims are not semantically verified.",
            }
            record["unsupported_claim_evaluation"] = unsupported_result

        if not args.retrieval_only:
            records_by_id[case["id"]] = record
            write_checkpoint(current_result(), args.output, args.results_csv)
        print(f"{progress_prefix} complete", flush=True)
    return current_result()


def _combined_claim_rate(
    unsupported_rows: list[dict[str, Any]],
    prohibited_rows: list[dict[str, Any]],
) -> float | None:
    """Combine claim rates over all evaluated answers, aligning by case ID."""
    if not unsupported_rows:
        return None
    prohibited_by_id = {row["id"]: row["passed"] for row in prohibited_rows}
    flagged = sum(
        (not row["passed"]) or not prohibited_by_id.get(row["id"], True)
        for row in unsupported_rows
    )
    return flagged / len(unsupported_rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--retrieval-only", dest="retrieval_only", action="store_true")
    mode.add_argument(
        "--with-answer-generation",
        dest="retrieval_only",
        action="store_false",
        help="Also generate answers and report answer-quality metrics.",
    )
    parser.set_defaults(retrieval_only=True)
    parser.add_argument(
        "--resume",
        "--missing-only",
        dest="resume",
        action="store_true",
        help="Reuse successful cases in the latest results and run missing or failed cases only.",
    )
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--top-k", type=int, default=5)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "evals/results/latest.json"
    )
    parser.add_argument(
        "--results-csv", type=Path, default=ROOT / "evals/results/latest.csv"
    )
    args = parser.parse_args()
    if args.limit is not None and args.limit < 1:
        parser.error("--limit must be at least 1")
    if args.top_k < 1:
        parser.error("--top-k must be at least 1")
    result = evaluate(args)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n")
    write_results_csv(result, args.results_csv)
    print(json.dumps(result["metrics"], indent=2))
    print(f"Wrote {args.output}")
    print(f"Wrote {args.results_csv}")
    print("Wrote evals/data/gold_dataset.csv")


if __name__ == "__main__":
    main()
